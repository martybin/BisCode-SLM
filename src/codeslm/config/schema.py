def _parse_sources(raw: Any, errors: list[str]) -> tuple[DataSource, ...] | None:
    if not isinstance(raw, list) or not raw:
        errors.append("sources must be a non-empty list")
        return None
    sources: list[DataSource] = []
    seen_ids: set[str] = set()
    for index, item in enumerate(raw):
        path = f"sources[{index}]"
        if not isinstance(item, Mapping):
            errors.append(f"{path} must be a mapping")
            continue
        _reject_unknown(
            item,
            {
                "id",
                "repo_id",
                "split",
                "role",
                "enabled",
                "language",
                "streaming",
                "revision",
                "max_kept_files",
                "reason",
            },
            path,
            errors,
        )
        source_id = _expect_nonempty_str(item, "id", errors, path)
        repo_id = _expect_nonempty_str(item, "repo_id", errors, path)
        role = _expect_choice(item, "role", errors, path, set(SOURCE_ROLES))
        enabled = _expect_bool(item, "enabled", errors, path)
        if source_id is None or repo_id is None or role is None or enabled is None:
            continue
        if source_id in seen_ids:
            errors.append(f"{path}.id {source_id!r} is duplicated")
        seen_ids.add(source_id)
        split = _optional_str(item, "split", errors, path)
        language = _optional_str(item, "language", errors, path)
        streaming = _optional_bool(item, "streaming", errors, path)
        revision = _optional_str(item, "revision", errors, path, allow_null=True)
        max_kept = _optional_int(item, "max_kept_files", errors, path, minimum=1)
        reason = _optional_str(item, "reason", errors, path)
        if enabled:
            if role not in ENABLED_ROLES:
                errors.append(f"{path} role {role!r} cannot be enabled")
            if split is None:
                errors.append(f"{path}.split is required when enabled")
            if language not in LANGUAGES:
                errors.append(f"{path}.language must be one of {list(LANGUAGES)} when enabled")
            if streaming is not True:
                errors.append(f"{path}.streaming must be true when enabled")
            if max_kept is None:
                errors.append(f"{path}.max_kept_files is required when enabled")
        elif not reason:
            errors.append(f"{path}.reason is required when the source is disabled")
        sources.append(
            DataSource(
                id=source_id,
                repo_id=repo_id,
                role=role,
                enabled=enabled,
                split=split,
                language=language,
                streaming=streaming,
                revision=revision,
                max_kept_files=max_kept,
                reason=reason,
            )
        )
    if len(sources) != len(raw):
        return None
    return tuple(sources)


def _check_source_consistency(
    sources: tuple[DataSource, ...] | None,
    mixture: Mapping[str, float] | None,
    split: tuple[str, str, str, bool] | None,
    errors: list[str],
) -> None:
    if sources is None or mixture is None or split is None:
        return
    enabled = [source for source in sources if source.enabled]
    train_sources = [source for source in enabled if source.role == "train"]
    valid_sources = [source for source in enabled if source.role == "validation"]
    if not train_sources:
        errors.append("sources need an enabled train source")
    if not valid_sources:
        errors.append("sources need an enabled validation source")
    _, train_repo, validation_repo, _ = split
    if train_sources and train_repo not in {source.repo_id for source in train_sources}:
        errors.append("split.train_repo does not match an enabled train source")
    if valid_sources and validation_repo not in {source.repo_id for source in valid_sources}:
        errors.append("split.validation_repo does not match an enabled validation source")
    covered = {source.language for source in train_sources}
    for language, weight in mixture.items():
        if weight > 0.0 and language not in covered:
            errors.append(f"mixture.{language} is {weight} but no enabled train source provides it")


