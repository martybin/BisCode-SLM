@dataclass(frozen=True)
class BatchSpec:
    seq_len: int
    micro_batch_size: int
    gradient_accumulation_steps: int

    @property
    def tokens_per_update(self) -> int:
        return self.seq_len * self.micro_batch_size * self.gradient_accumulation_steps


