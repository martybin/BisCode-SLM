def _parse_optimization(raw: Mapping[str, Any] | None, errors: list[str]) -> OptimizationSpec | None:
    if raw is None:
        return None
    _reject_unknown(
        raw,
        {
            "optimizer",
            "learning_rate",
            "weight_decay",
            "betas",
            "eps",
            "warmup_steps",
            "min_lr_ratio",
            "grad_clip_norm",
        },
        "optimization",
        errors,
    )
    optimizer = _expect_choice(raw, "optimizer", errors, "optimization", {"adamw"})
    learning_rate = _expect_float(raw, "learning_rate", errors, "optimization", minimum=0.0, exclusive_min=True)
    weight_decay = _expect_float(raw, "weight_decay", errors, "optimization", minimum=0.0)
    eps = _expect_float(raw, "eps", errors, "optimization", minimum=0.0, exclusive_min=True)
    warmup_steps = _expect_int(raw, "warmup_steps", errors, "optimization", minimum=0)
    min_lr_ratio = _expect_float(raw, "min_lr_ratio", errors, "optimization", minimum=0.0, maximum=1.0)
    grad_clip_norm = _expect_float(raw, "grad_clip_norm", errors, "optimization", minimum=0.0, exclusive_min=True)
    betas_raw = raw.get("betas")
    betas: tuple[float, float] | None = None
    if (
        not isinstance(betas_raw, list)
        or len(betas_raw) != 2
        or any(isinstance(item, bool) or not isinstance(item, (int, float)) for item in betas_raw)
    ):
        errors.append("optimization.betas must be a list of two numbers in (0, 1)")
    else:
        beta1 = float(betas_raw[0])
        beta2 = float(betas_raw[1])
        if not (0.0 < beta1 < 1.0 and 0.0 < beta2 < 1.0):
            errors.append("optimization.betas must each be in (0, 1)")
        else:
            betas = (beta1, beta2)
    values = (optimizer, learning_rate, weight_decay, eps, warmup_steps, min_lr_ratio, grad_clip_norm, betas)
    if any(value is None for value in values):
        return None
    assert optimizer is not None and learning_rate is not None and weight_decay is not None
    assert eps is not None and warmup_steps is not None and min_lr_ratio is not None
    assert grad_clip_norm is not None and betas is not None
    return OptimizationSpec(
        optimizer=optimizer,
        learning_rate=learning_rate,
        weight_decay=weight_decay,
        betas=betas,
        eps=eps,
        warmup_steps=warmup_steps,
        min_lr_ratio=min_lr_ratio,
        grad_clip_norm=grad_clip_norm,
    )


