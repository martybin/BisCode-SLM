def load_training_config(path: Path | str, project_root: Path | str | None = None) -> TrainingConfig:
    """Load a training file and the model and data files it names."""
    config_path = Path(path)
    root = Path(project_root).resolve() if project_root is not None else find_project_root(config_path)
    data = _load_mapping(config_path)
    errors: list[str] = []
    _reject_unknown(
        data,
        {
            "schema_version",
            "experiment_name",
            "model_config",
            "data_config",
            "seed",
            "runtime",
            "optimization",
            "batch",
            "budget",
            "checkpoint",
            "logging",
            "early_stopping",
        },
        "training config",
        errors,
    )
    schema_version = _expect_int(data, "schema_version", errors, "training config", allowed={SCHEMA_VERSION})
    experiment_name = _expect_nonempty_str(data, "experiment_name", errors, "training config")
    seed = _expect_int(data, "seed", errors, "training config", minimum=0)
    model_config_path = _expect_relative_path(data, "model_config", errors, "training config", root)
    data_config_path = _expect_relative_path(data, "data_config", errors, "training config", root)
    runtime = _parse_runtime(_expect_mapping(data, "runtime", errors, "training config"), errors)
    optimization = _parse_optimization(
        _expect_mapping(data, "optimization", errors, "training config"),
        errors,
    )
    batch = _parse_batch(_expect_mapping(data, "batch", errors, "training config"), errors)
    budget = _parse_budget(_expect_mapping(data, "budget", errors, "training config"), errors)
    checkpoint = _parse_checkpoint(_expect_mapping(data, "checkpoint", errors, "training config"), errors)
    logging_spec = _parse_logging(_expect_mapping(data, "logging", errors, "training config"), errors)
    early_stopping = _parse_early_stopping(
        _expect_mapping(data, "early_stopping", errors, "training config"),
        errors,
    )
    model = _load_nested_model(root, model_config_path, errors)
    data_config = _load_nested_data(root, data_config_path, errors)
    if model is not None and batch is not None and batch.seq_len > model.model.max_seq_len:
        errors.append(
            f"batch.seq_len {batch.seq_len} exceeds model.max_seq_len {model.model.max_seq_len}"
        )
    required = (
        schema_version,
        experiment_name,
        seed,
        model_config_path,
        data_config_path,
        runtime,
        optimization,
        batch,
        budget,
        checkpoint,
        logging_spec,
        early_stopping,
        model,
        data_config,
    )
    if errors or any(piece is None for piece in required):
        raise ConfigError(errors or ["training config is incomplete"], config_path)
    assert experiment_name is not None and seed is not None and schema_version is not None
    assert model_config_path is not None and data_config_path is not None
    assert runtime is not None and optimization is not None and batch is not None
    assert budget is not None and checkpoint is not None and logging_spec is not None
    assert early_stopping is not None and model is not None and data_config is not None
    return TrainingConfig(
        schema_version=schema_version,
        experiment_name=experiment_name,
        model_config_path=model_config_path,
        data_config_path=data_config_path,
        seed=seed,
        runtime=runtime,
        optimization=optimization,
        batch=batch,
        budget=budget,
        checkpoint=checkpoint,
        logging=logging_spec,
        early_stopping=early_stopping,
        model=model,
        data=data_config,
        path=config_path.resolve(),
        project_root=root,
    )


def launch_blockers(training: TrainingConfig) -> tuple[str, ...]:
    """Reasons a training process must refuse to start.

    A config can be valid and still be blocked. The shipped smoke config is
    valid, and it stays blocked while ``download_enabled`` is false.
    """
    blockers: list[str] = []
    if not training.data.download_enabled:
        blockers.append(
            "data.download_enabled is false. Training stays off until a download "
            "is approved or a future synthetic-corpus flag is set."
        )
    return tuple(blockers)


def _load_nested_model(root: Path, relative: str | None, errors: list[str]) -> ModelConfig | None:
    if relative is None:
        return None
    path = root / relative
    if not path.is_file():
        errors.append(f"model_config does not exist: {relative}")
        return None
    try:
        return load_model_config(path)
    except ConfigError as exc:
        errors.extend(f"model_config: {message}" for message in exc.errors)
        return None


def _load_nested_data(root: Path, relative: str | None, errors: list[str]) -> DataConfig | None:
    if relative is None:
        return None
    path = root / relative
    if not path.is_file():
        errors.append(f"data_config does not exist: {relative}")
        return None
    try:
        return load_data_config(path)
    except ConfigError as exc:
        errors.extend(f"data_config: {message}" for message in exc.errors)
        return None


def _parse_arch(raw: Mapping[str, Any] | None, errors: list[str]) -> ModelArch | None:
    if raw is None:
        return None
    _reject_unknown(
        raw,
        {
            "architecture",
            "vocab_size",
            "d_model",
            "n_layers",
            "n_heads",
            "n_kv_heads",
            "intermediate_size",
            "max_seq_len",
            "rope_theta",
            "rms_norm_eps",
            "tie_embeddings",
            "bias",
            "dropout",
            "init_std",
        },
        "model",
        errors,
    )
    architecture = _expect_choice(raw, "architecture", errors, "model", {"decoder_only"})
    vocab_size = _expect_int(raw, "vocab_size", errors, "model", minimum=len(SPECIAL_TOKEN_KEYS), maximum=200_000)
    d_model = _expect_int(raw, "d_model", errors, "model", minimum=1, maximum=8192)
    n_layers = _expect_int(raw, "n_layers", errors, "model", minimum=1, maximum=128)
    n_heads = _expect_int(raw, "n_heads", errors, "model", minimum=1, maximum=256)
    n_kv_heads = _expect_int(raw, "n_kv_heads", errors, "model", minimum=1, maximum=256)
    intermediate_size = _expect_int(raw, "intermediate_size", errors, "model", minimum=1, maximum=32768)
    max_seq_len = _expect_int(raw, "max_seq_len", errors, "model", minimum=1, maximum=262144)
    rope_theta = _expect_float(raw, "rope_theta", errors, "model", minimum=0.0, exclusive_min=True)
    rms_norm_eps = _expect_float(raw, "rms_norm_eps", errors, "model", minimum=0.0, exclusive_min=True, maximum=1.0)
    tie_embeddings = _expect_bool(raw, "tie_embeddings", errors, "model")
    bias = _expect_bool(raw, "bias", errors, "model")
    dropout = _expect_float(raw, "dropout", errors, "model", minimum=0.0, maximum=1.0, exclusive_max=True)
    init_std = _expect_float(raw, "init_std", errors, "model", minimum=0.0, exclusive_min=True, maximum=1.0)
    values = (
        architecture,
        vocab_size,
        d_model,
        n_layers,
        n_heads,
        n_kv_heads,
        intermediate_size,
        max_seq_len,
        rope_theta,
        rms_norm_eps,
        tie_embeddings,
        bias,
        dropout,
        init_std,
    )
    if any(value is None for value in values):
        return None
    assert architecture is not None and vocab_size is not None and d_model is not None
    assert n_layers is not None and n_heads is not None and n_kv_heads is not None
    assert intermediate_size is not None and max_seq_len is not None and rope_theta is not None
    assert rms_norm_eps is not None and tie_embeddings is not None and bias is not None
    assert dropout is not None and init_std is not None
    if d_model % n_heads != 0:
        errors.append(f"model.d_model {d_model} is not divisible by n_heads {n_heads}")
    elif n_heads % n_kv_heads != 0:
        errors.append(f"model.n_heads {n_heads} is not divisible by n_kv_heads {n_kv_heads}")
    return ModelArch(
        architecture=architecture,
        vocab_size=vocab_size,
        d_model=d_model,
        n_layers=n_layers,
        n_heads=n_heads,
        n_kv_heads=n_kv_heads,
        intermediate_size=intermediate_size,
        max_seq_len=max_seq_len,
        rope_theta=rope_theta,
        rms_norm_eps=rms_norm_eps,
        tie_embeddings=tie_embeddings,
        bias=bias,
        dropout=dropout,
        init_std=init_std,
    )


def _parse_tokenizer(raw: Mapping[str, Any] | None, errors: list[str]) -> TokenizerSpec | None:
    if raw is None:
        return None
    _reject_unknown(
        raw,
        {"type", "vocab_size", "add_prefix_space", "special_tokens"},
        "tokenizer",
        errors,
    )
    tokenizer_type = _expect_choice(raw, "type", errors, "tokenizer", {"byte_level_bpe"})
    vocab_size = _expect_int(raw, "vocab_size", errors, "tokenizer", minimum=len(SPECIAL_TOKEN_KEYS), maximum=200_000)
    add_prefix_space = _expect_bool(raw, "add_prefix_space", errors, "tokenizer")
    specials_raw = _expect_mapping(raw, "special_tokens", errors, "tokenizer")
    specials = _parse_specials(specials_raw, errors)
    if tokenizer_type is None or vocab_size is None or add_prefix_space is None or specials is None:
        return None
    if add_prefix_space:
        errors.append("tokenizer.add_prefix_space must be false for source code")
    return TokenizerSpec(
        type=tokenizer_type,
        vocab_size=vocab_size,
        add_prefix_space=add_prefix_space,
        special_tokens=specials,
    )


def _parse_specials(raw: Mapping[str, Any] | None, errors: list[str]) -> Mapping[str, str] | None:
    if raw is None:
        return None
    _reject_unknown(raw, set(SPECIAL_TOKEN_KEYS), "tokenizer.special_tokens", errors)
    missing = [key for key in SPECIAL_TOKEN_KEYS if key not in raw]
    if missing:
        errors.append(f"tokenizer.special_tokens missing {missing}")
        return None
    tokens: dict[str, str] = {}
    for key in SPECIAL_TOKEN_KEYS:
        value = raw[key]
        if not isinstance(value, str) or not value or any(character.isspace() for character in value):
            errors.append(f"tokenizer.special_tokens.{key} must be a non-empty token without whitespace")
            return None
        tokens[key] = value
    if len(set(tokens.values())) != len(tokens):
        errors.append("tokenizer.special_tokens values must be unique")
        return None
    return MappingProxyType(tokens)


def _parse_data_tokenizer(
    raw: Mapping[str, Any] | None,
    errors: list[str],
) -> tuple[str | None, tuple[str, ...] | None]:
    if raw is None:
        return None, None
    _reject_unknown(raw, {"train_on", "forbid_roles"}, "data.tokenizer", errors)
    train_on = _expect_choice(raw, "train_on", errors, "data.tokenizer", {"train"})
    forbid = raw.get("forbid_roles")
    if not isinstance(forbid, list) or not forbid or not all(isinstance(item, str) and item for item in forbid):
        errors.append("data.tokenizer.forbid_roles must be a non-empty list of roles")
        return train_on, None
    unknown = sorted(set(forbid) - set(SOURCE_ROLES))
    if unknown:
        errors.append(f"data.tokenizer.forbid_roles has unknown roles {unknown}")
    if train_on is not None and train_on in forbid:
        errors.append("data.tokenizer.train_on is also forbidden")
    return train_on, tuple(forbid)


def _parse_mixture(raw: Mapping[str, Any] | None, errors: list[str]) -> Mapping[str, float] | None:
    if raw is None:
        return None
    _reject_unknown(raw, set(LANGUAGES), "mixture", errors)
    missing = [language for language in LANGUAGES if language not in raw]
    if missing:
        errors.append(f"mixture missing {missing}")
        return None
    mixture: dict[str, float] = {}
    for language in LANGUAGES:
        value = raw[language]
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            errors.append(f"mixture.{language} must be a number")
            return None
        weight = float(value)
        if weight < 0.0 or weight > 1.0:
            errors.append(f"mixture.{language} must be between 0 and 1")
            return None
        mixture[language] = weight
    total = sum(mixture.values())
    if abs(total - 1.0) > 1e-6:
        errors.append(f"mixture weights sum to {total}, expected 1")
    return MappingProxyType(mixture)


def _parse_license(
    raw: Mapping[str, Any] | None,
    errors: list[str],
) -> tuple[tuple[str, ...] | None, tuple[str, ...] | None, bool | None]:
    if raw is None:
        return None, None, None
    _reject_unknown(raw, {"allow", "exclude", "quarantine_unknown"}, "license", errors)
    allow = _expect_string_list(raw, "allow", errors, "license")
    exclude = _expect_string_list(raw, "exclude", errors, "license")
    quarantine_unknown = _expect_bool(raw, "quarantine_unknown", errors, "license")
    if allow is not None and exclude is not None:
        overlap = sorted(set(allow) & set(exclude))
        if overlap:
            errors.append(f"license allow and exclude overlap: {overlap}")
        if len(allow) != len(set(allow)) or len(exclude) != len(set(exclude)):
            errors.append("license lists must not contain duplicates")
    return allow, exclude, quarantine_unknown


def _parse_filters(
    raw: Mapping[str, Any] | None,
    errors: list[str],
) -> tuple[int, int, bool, bool, int] | None:
    if raw is None:
        return None
    _reject_unknown(
        raw,
        {"min_chars", "max_chars", "drop_autogenerated", "drop_empty", "max_files_per_repo"},
        "filters",
        errors,
    )
    min_chars = _expect_int(raw, "min_chars", errors, "filters", minimum=0)
    max_chars = _expect_int(raw, "max_chars", errors, "filters", minimum=1)
    drop_autogenerated = _expect_bool(raw, "drop_autogenerated", errors, "filters")
    drop_empty = _expect_bool(raw, "drop_empty", errors, "filters")
    max_files_per_repo = _expect_int(raw, "max_files_per_repo", errors, "filters", minimum=1)
