def find_project_root(start: Path | None = None) -> Path:
    """Walk parents until a directory contains both ``pyproject.toml`` and ``configs``."""
    origin = Path.cwd() if start is None else Path(start)
    current = origin.resolve()
    if current.is_file():
        current = current.parent
    for candidate in (current, *current.parents):
        if (candidate / "pyproject.toml").is_file() and (candidate / "configs").is_dir():
            return candidate
    raise ConfigError([f"could not find the project root from {current}"])


def load_model_config(path: Path | str) -> ModelConfig:
    config_path = Path(path)
    data = _load_mapping(config_path)
    errors: list[str] = []
    _reject_unknown(
        data,
        {"schema_version", "name", "model", "tokenizer", "parameter_count"},
        "model config",
        errors,
    )
    schema_version = _expect_int(data, "schema_version", errors, "model config", allowed={SCHEMA_VERSION})
    name = _expect_nonempty_str(data, "name", errors, "model config")
    arch = _parse_arch(_expect_mapping(data, "model", errors, "model config"), errors)
    tokenizer = _parse_tokenizer(
        _expect_mapping(data, "tokenizer", errors, "model config"),
        errors,
    )
    parameter_count = _expect_int(data, "parameter_count", errors, "model config", minimum=1)
    if arch is not None and tokenizer is not None and arch.vocab_size != tokenizer.vocab_size:
        errors.append(
            "model.vocab_size and tokenizer.vocab_size differ "
            f"({arch.vocab_size} vs {tokenizer.vocab_size})"
        )
    if arch is not None and parameter_count is not None and _shape_is_countable(arch):
        computed = count_parameters(
            vocab_size=arch.vocab_size,
            d_model=arch.d_model,
            n_layers=arch.n_layers,
            n_heads=arch.n_heads,
            n_kv_heads=arch.n_kv_heads,
            intermediate_size=arch.intermediate_size,
            tie_embeddings=arch.tie_embeddings,
            bias=arch.bias,
        )
        if computed != parameter_count:
            errors.append(
                f"parameter_count is {parameter_count}, architecture formula gives {computed}"
            )
    if errors or arch is None or tokenizer is None or name is None or parameter_count is None or schema_version is None:
        raise ConfigError(errors or ["model config is incomplete"], config_path)
    return ModelConfig(
        schema_version=schema_version,
        name=name,
        model=arch,
        tokenizer=tokenizer,
        parameter_count=parameter_count,
        path=config_path.resolve(),
    )


