def _shape_is_countable(arch: ModelArch) -> bool:
    return arch.d_model % arch.n_heads == 0 and arch.n_heads % arch.n_kv_heads == 0


def _load_mapping(path: Path) -> Mapping[str, Any]:
    if not path.is_file():
        raise ConfigError([f"file does not exist: {path}"], path)
    try:
        loaded = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        raise ConfigError([f"invalid YAML: {exc}"], path) from exc
    if not isinstance(loaded, Mapping):
        raise ConfigError(["YAML root must be a mapping"], path)
    return loaded


def _reject_unknown(raw: Mapping[str, Any], allowed: set[str], label: str, errors: list[str]) -> None:
    unknown = sorted(set(raw) - allowed)
    if unknown:
        errors.append(f"{label}: unknown keys {unknown}")


def _expect_mapping(
    raw: Mapping[str, Any],
    key: str,
    errors: list[str],
    label: str,
) -> Mapping[str, Any] | None:
    if key not in raw:
        errors.append(f"{label}: missing {key}")
        return None
    value = raw[key]
    if not isinstance(value, Mapping):
        errors.append(f"{label}.{key} must be a mapping")
        return None
    return value


def _expect_int(
    raw: Mapping[str, Any],
    key: str,
    errors: list[str],
    label: str,
    *,
    minimum: int | None = None,
    maximum: int | None = None,
    allowed: set[int] | None = None,
) -> int | None:
    if key not in raw:
        errors.append(f"{label}: missing {key}")
        return None
    value = raw[key]
    if isinstance(value, bool) or not isinstance(value, int):
        errors.append(f"{label}.{key} must be an integer")
        return None
    if allowed is not None and value not in allowed:
        errors.append(f"{label}.{key} must be one of {sorted(allowed)}")
        return None
    if minimum is not None and value < minimum:
        errors.append(f"{label}.{key} must be >= {minimum}")
        return None
    if maximum is not None and value > maximum:
        errors.append(f"{label}.{key} must be <= {maximum}")
        return None
    return value


def _expect_float(
    raw: Mapping[str, Any],
    key: str,
    errors: list[str],
    label: str,
    *,
    minimum: float | None = None,
    maximum: float | None = None,
    exclusive_min: bool = False,
    exclusive_max: bool = False,
) -> float | None:
    if key not in raw:
        errors.append(f"{label}: missing {key}")
        return None
    value = raw[key]
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        errors.append(f"{label}.{key} must be a number")
        return None
    number = float(value)
    if minimum is not None and (number <= minimum if exclusive_min else number < minimum):
        errors.append(f"{label}.{key} is below the allowed minimum")
        return None
    if maximum is not None and (number >= maximum if exclusive_max else number > maximum):
        errors.append(f"{label}.{key} is above the allowed maximum")
        return None
    return number


