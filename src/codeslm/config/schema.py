def _expect_choice(
    raw: Mapping[str, Any],
    key: str,
    errors: list[str],
    label: str,
    choices: set[str],
) -> str | None:
    value = _expect_nonempty_str(raw, key, errors, label)
    if value is None:
        return None
    if value not in choices:
        errors.append(f"{label}.{key} must be one of {sorted(choices)}")
