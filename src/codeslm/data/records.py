"""In-memory code records. This module does not read from the network."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class CodeRecord:
    """One source file and the provenance needed to filter it."""

    source_id: str
    repo_name: str
    path: str
    content: str
    license: str | None
    language: str
    autogenerated: bool = False


@dataclass(frozen=True)
class Decision:
    """Why a record was kept, excluded, or quarantined.

    ``detail`` may name a hash, a similarity, or a rule id. It must not contain
    the file body or a matched secret.
    """

    split: str
    record_index: int
    source_id: str
    repo_name: str
    path: str
    license: str | None
    language: str
    disposition: str
    reason: str
    detail: str = ""


def decision_for(record: CodeRecord, *, split: str, record_index: int, disposition: str, reason: str, detail: str = "") -> Decision:
    return Decision(
        split=split,
        record_index=record_index,
        source_id=record.source_id,
        repo_name=record.repo_name,
        path=record.path,
        license=record.license,
        language=record.language,
        disposition=disposition,
        reason=reason,
        detail=detail,
    )
