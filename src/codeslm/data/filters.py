"""Content and license filters.

Each record receives one disposition. Unknown licenses are quarantined when the
config says so, and they are still excluded from training when it does not.
Secret matches are quarantined and the matched text is not copied into the log.
"""

from __future__ import annotations

import re

from codeslm.config.schema import DataConfig
from codeslm.data.records import CodeRecord, Decision, decision_for

KEEP = "keep"
EXCLUDE = "exclude"
QUARANTINE = "quarantine"

_VENDOR_PARTS = {
    "node_modules",
    "vendor",
    "third_party",
    "third-party",
    "site-packages",
    "dist",
    "__pycache__",
}
_NON_CODE_SUFFIXES = (".html", ".htm", ".md", ".rst", ".pdf", ".png", ".jpg", ".jpeg", ".gif", ".webp")
_GENERATED_MARKERS = (
    "do not edit",
    "auto-generated",
    "autogenerated",
    "generated by",
    "@generated",
    "automatically generated",
)
_SECRET_RULES: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("private_key", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----")),
    ("aws_access_key", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("github_token", re.compile(r"\bgh[pousr]_[A-Za-z0-9]{20,}\b")),
    ("slack_token", re.compile(r"\bxox[baprs]-[A-Za-z0-9-]{10,}")),
    ("assigned_secret", re.compile(r"(?i)\b(?:api_key|secret|password|token)\b\s*=\s*['\"][^'\"]{12,}['\"]")),
    ("ssn", re.compile(r"\b\d{3}-\d{2}-\d{4}\b")),
)
_MINIFIED_MIN_CHARS = 200
_MINIFIED_AVG_LINE = 200


def filter_records(records: list[CodeRecord], config: DataConfig, *, split: str) -> list[Decision]:
    """Return one decision per record, in the same order."""
    allow = {item.lower() for item in config.license_allow}
    exclude = {item.lower() for item in config.license_exclude}
    decisions: list[Decision] = []
    for index, record in enumerate(records):
        decisions.append(_decide(record, index, split, config, allow, exclude))
    return decisions


def _decide(
    record: CodeRecord,
    index: int,
    split: str,
    config: DataConfig,
    allow: set[str],
    exclude: set[str],
) -> Decision:
    content = record.content
    stripped = content.strip()
    if config.drop_empty and stripped == "":
        return _exclude(record, index, split, "empty")
    if len(content) < config.min_chars:
        return _exclude(record, index, split, "too_short")
    if len(content) > config.max_chars:
        return _exclude(record, index, split, "too_long")
    if _is_binary(content):
        return _exclude(record, index, split, "binary")
    if _is_vendor_path(record.path):
        return _exclude(record, index, split, "vendor_path")
    if record.path.lower().endswith(_NON_CODE_SUFFIXES):
        return _exclude(record, index, split, "non_code")
    if config.drop_autogenerated and (record.autogenerated or _looks_generated(content)):
        return _exclude(record, index, split, "generated")
    if _looks_minified(content):
        return _exclude(record, index, split, "minified")
    secret_rule = _secret_rule(content)
    if secret_rule is not None:
        return _make(record, index, split, QUARANTINE, "secret_suspected", secret_rule)
    return _license_decision(record, index, split, config, allow, exclude)


def _license_decision(
    record: CodeRecord,
    index: int,
    split: str,
    config: DataConfig,
    allow: set[str],
    exclude: set[str],
) -> Decision:
    label = (record.license or "").strip().lower()
    if label in allow:
        return _make(record, index, split, KEEP, "kept")
    if label in exclude:
        return _exclude(record, index, split, "license_excluded", label or "empty")
    if config.quarantine_unknown:
        return _make(record, index, split, QUARANTINE, "license_unknown", label or "empty")
    return _exclude(record, index, split, "license_unreviewed", label or "empty")


def _is_binary(content: str) -> bool:
    if "\x00" in content:
        return True
    if not content:
        return False
    disallowed = 0
    for character in content:
        code = ord(character)
        if character in "\n\t\r":
            continue
        if code < 32:
            disallowed += 1
    return disallowed / len(content) > 0.30


def _is_vendor_path(path: str) -> bool:
    parts = {part.lower() for part in path.replace("\\", "/").split("/") if part}
    return bool(parts & _VENDOR_PARTS)


def _looks_generated(content: str) -> bool:
    lowered = content.lower()
    return any(marker in lowered for marker in _GENERATED_MARKERS)


def _looks_minified(content: str) -> bool:
    if len(content) < _MINIFIED_MIN_CHARS:
        return False
    lines = content.splitlines() or [content]
    average = len(content) / len(lines)
    return average >= _MINIFIED_AVG_LINE


def _secret_rule(content: str) -> str | None:
    for name, pattern in _SECRET_RULES:
        if pattern.search(content):
            return name
    return None


def _exclude(record: CodeRecord, index: int, split: str, reason: str, detail: str = "") -> Decision:
    return _make(record, index, split, EXCLUDE, reason, detail)


def _make(record: CodeRecord, index: int, split: str, disposition: str, reason: str, detail: str = "") -> Decision:
    return decision_for(
        record,
        split=split,
        record_index=index,
        disposition=disposition,
        reason=reason,
        detail=detail,
    )
