def test_license_and_content_filters_log_every_record(tmp_path: Path) -> None:
    config = _config(min_chars=40, max_chars=500, max_files_per_repo=10)
    secret = "correct-horse-battery"
    records = [
        _record("keep.py", FUNCTION, "MIT", repo="ada/lib"),
        _record("copy.py", FUNCTION, "mit", repo="ada/lib"),
        _record("gpl.py", FUNCTION, "gpl-3.0", repo="ada/lib"),
        _record("mystery.py", FUNCTION, None, repo="ada/other"),
        _record("short.py", "x = 1\n", "mit", repo="ada/lib"),
        _record("blank.py", "   \n", "mit", repo="ada/lib"),
        _record("gen.py", FUNCTION + "\n# auto-generated by the tool\n", "mit", repo="ada/lib"),
        _record("vendor/pkg.py", FUNCTION, "mit", repo="ada/lib"),
        _record("readme.md", FUNCTION, "mit", repo="ada/lib"),
        _record("min.py", "x=" + ("a+b;" * 80), "mit", repo="ada/lib"),
        _record("bin.py", FUNCTION + "\x00", "mit", repo="ada/lib"),
        _record("keys.py", FUNCTION + f"\npassword = '{secret}'\n", "mit", repo="ada/lib"),
    ]
    result = run_pipeline(records, config, output_dir=tmp_path)
    assert len(result.train_decisions) == len(records)
    reasons = {decision.path: decision.reason for decision in result.train_decisions}
    assert reasons["keep.py"] == "kept"
    assert reasons["copy.py"] == "exact_duplicate"
    assert reasons["gpl.py"] == "license_excluded"
    assert reasons["mystery.py"] == "license_unknown"
    assert result.train_decisions[3].disposition == "quarantine"
    assert reasons["short.py"] == "too_short"
    assert reasons["blank.py"] == "empty"
    assert reasons["gen.py"] == "generated"
    assert reasons["vendor/pkg.py"] == "vendor_path"
    assert reasons["readme.md"] == "non_code"
    assert reasons["min.py"] == "minified"
    assert reasons["bin.py"] == "binary"
    assert reasons["keys.py"] == "secret_suspected"
    assert result.train_decisions[11].disposition == "quarantine"
    assert result.train_decisions[11].detail == "assigned_secret"
    assert [record.path for record in result.train] == ["keep.py"]
    logged = (tmp_path / "decisions.jsonl").read_text(encoding="utf-8")
    report = (tmp_path / "license_report.json").read_text(encoding="utf-8")
    assert secret not in logged
    assert secret not in report
    license_report = json.loads(report)
    assert license_report["unknown_examples"][0]["license"] == "empty"
    manifest = yaml.safe_load((tmp_path / "dataset_manifest.yaml").read_text(encoding="utf-8"))
    assert manifest["network_fetch"] is False
    assert manifest["download_enabled"] is False


def test_near_duplicate_and_repository_cap() -> None:
    config = _config(min_chars=40, max_chars=20_000, max_files_per_repo=2, jaccard_threshold=0.85)
    original = _lines("token")
    records = [
        _record("a.py", original, "mit", repo="ada/lib"),
        _record("b.py", original.replace("token90", "tokenCHANGED"), "mit", repo="ada/lib"),
        _record("c.py", _lines("alpha"), "apache-2.0", repo="ada/lib"),
        _record("d.py", _lines("beta"), "apache-2.0", repo="ada/lib"),
        _record("e.py", _lines("gamma"), "mit", repo="ada/lib"),
    ]
    result = run_pipeline(records, config)
    reasons = {decision.path: decision.reason for decision in result.train_decisions}
    assert reasons["a.py"] == "kept"
    assert reasons["b.py"] == "near_duplicate"
    assert reasons["c.py"] == "kept"
    assert reasons["d.py"] == "repo_file_cap"
    assert reasons["e.py"] == "repo_file_cap"
    assert {record.path for record in result.train} == {"a.py", "c.py"}


def test_validation_repository_and_content_do_not_leak_into_training() -> None:
    config = _config(min_chars=40, max_chars=5000, max_files_per_repo=10)
    shared = FUNCTION + "shared = True\n"
    train_records = [
        _record("same_repo.py", FUNCTION + "train_only = 1\n", "mit", repo="ada/shared"),
        _record("same_body.py", shared, "mit", repo="ada/train-only"),
        _record("clean.py", FUNCTION + "clean = 1\n", "mit", repo="ada/clean"),
    ]
    validation_records = [
        _record("heldout.py", FUNCTION + "validation = 1\n", "mit", repo="ada/shared"),
        _record("held_body.py", shared, "mit", repo="ada/validation"),
    ]
    result = run_pipeline(train_records, config, validation_records=validation_records)
    reasons = {decision.path: decision.reason for decision in result.train_decisions}
    assert reasons["same_repo.py"] == "validation_repo_overlap"
    assert reasons["same_body.py"] == "validation_content_overlap"
    assert reasons["clean.py"] == "kept"
    assert [record.path for record in result.train] == ["clean.py"]
    assert [record.path for record in result.validation] == ["heldout.py", "held_body.py"]


def test_repository_assignment_keeps_a_repo_together() -> None:
    records = [
        _record("a.py", FUNCTION, "mit", repo="one/repo"),
        _record("b.py", FUNCTION + "x = 2\n", "mit", repo="one/repo"),
        _record("c.py", FUNCTION + "y = 3\n", "mit", repo="two/repo"),
    ]
    train, validation = assign_repositories(records, validation_fraction=0.0, seed=7)
    assert len(train) == 3 and validation == []
    train, validation = assign_repositories(records, validation_fraction=1.0, seed=7)
    assert train == [] and len(validation) == 3
    train, validation = assign_repositories(records, validation_fraction=0.5, seed=7)
    train_repos = {record.repo_name for record in train}
    validation_repos = {record.repo_name for record in validation}
    assert train_repos.isdisjoint(validation_repos)
    assert train_repos | validation_repos == {"one/repo", "two/repo"}


def test_packing_resets_positions_and_blocks_cross_document_labels() -> None:
    rows = pack_token_rows([[10, 11, 3], [20, 3]], seq_len=8, pad_id=0)
    assert len(rows) == 1
    row = rows[0]
    assert row.input_ids == (10, 11, 3, 20, 3, 0, 0, 0)
    assert row.position_ids == (0, 1, 2, 0, 1, 0, 0, 0)
    assert row.block_ids == (0, 0, 0, 1, 1, -1, -1, -1)
    assert row.attention_mask == (1, 1, 1, 1, 1, 0, 0, 0)
    assert row.labels[0:5] == (11, 3, IGNORE_INDEX, 3, IGNORE_INDEX)
    assert all(label == IGNORE_INDEX for label in row.labels[5:])
    mask = causal_block_mask(row.block_ids)
    assert mask[3][0] is False
    assert mask[3][3] is True
    assert mask[1][0] is True

    long_row = list(range(10, 16))
    split = pack_token_rows([long_row], seq_len=4, pad_id=0)
    assert [item.input_ids for item in split] == [(10, 11, 12, 13), (14, 15, 0, 0)]
    assert split[1].position_ids == (4, 5, 0, 0)
    assert split[0].block_ids == (0, 0, 0, 0)
    assert split[1].block_ids == (0, 0, -1, -1)


def test_pack_texts_appends_eos_and_roundtrips(tmp_path: Path) -> None:
    del tmp_path
    text = FUNCTION + "print('packed')\n"
    tokenizer = train_tokenizer([text, "SELECT id FROM users;\n"], _tokenizer_spec(), min_frequency=1)
    packed = pack_texts([text], tokenizer, seq_len=512)
    eos = tokenizer.token_id("eos")
    ids = [
        token
        for row in packed
        for token, keep in zip(row.input_ids, row.attention_mask, strict=True)
        if keep
    ]
    assert len(packed) == 1
    assert ids[-1] == eos
    assert tokenizer.decode(ids) == text + "<|eos|>"


def _config(**changes: object):
    config = load_data_config(ROOT / "configs/data/initial.yaml")
    return replace(config, **changes)


def _lines(prefix: str) -> str:
    words = [f"{prefix}{index}" for index in range(180)]
    return "\n".join(" ".join(words[start : start + 10]) for start in range(0, len(words), 10)) + "\n"


def _record(path: str, content: str, license_name: str | None, *, repo: str) -> CodeRecord:
    return CodeRecord(
        source_id="synthetic",
        repo_name=repo,
        path=path,
        content=content,
        license=license_name,
        language="python",
    )


def _tokenizer_spec() -> TokenizerSpec:
    shipped = load_model_config(ROOT / "configs/model/smoke.yaml").tokenizer
    return TokenizerSpec(
        type=shipped.type,
        vocab_size=300,
        add_prefix_space=False,
        special_tokens=dict(shipped.special_tokens),
    )
